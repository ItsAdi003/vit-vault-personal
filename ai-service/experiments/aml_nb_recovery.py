"""
AML experiment 1: does maximum-likelihood Naive Bayes learn the right model?

Ground truth = the hand-crafted conditional probability table of the live app,
read as Bernoulli parameters. We sample labelled tag sets from it, fit the
from-scratch BernoulliNaiveBayes on n examples, and measure
  * parameter error  mean |theta_hat - theta|          (consistency of the MLE)
  * test accuracy against the Bayes-optimal classifier (the true model)
over many random seeds.

Run:  python experiments/aml_nb_recovery.py
"""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _report import print_table, save_report  # noqa: E402

from config import CANDIDATE_LABELS  # noqa: E402
from ml.nb_model import BernoulliNaiveBayes  # noqa: E402
from services.classifier import DEFAULT_LIKELIHOOD, TAG_LIKELIHOODS  # noqa: E402

CLASSES = ["INSTITUTIONAL", "COMMITTEE"]
SIZES = [10, 20, 50, 100, 200, 500, 1000, 5000]
SEEDS = 20
TEST_N = 5000


def true_theta():
    return np.array([[TAG_LIKELIHOODS[c].get(t, DEFAULT_LIKELIHOOD) for t in CANDIDATE_LABELS] for c in CLASSES])


def sample(rng, theta, n):
    y = rng.integers(0, 2, n)
    X = (rng.random((n, theta.shape[1])) < theta[y]).astype(np.uint8)
    return X, y


def tagsets(X):
    return [[CANDIDATE_LABELS[j] for j in np.flatnonzero(r)] for r in X]


def main():
    theta = true_theta()
    oracle = BernoulliNaiveBayes(CANDIDATE_LABELS, CLASSES)
    oracle.theta_, oracle.log_prior_ = theta, np.log([0.5, 0.5])

    rng = np.random.default_rng(12345)
    Xt, yt = sample(rng, theta, TEST_N)
    test_sets = tagsets(Xt)
    bayes_acc = float(np.mean(oracle.predict_proba(test_sets).argmax(1) == yt))

    rows, mae_curve = [], []
    for n in SIZES:
        maes, accs = [], []
        for s in range(SEEDS):
            r = np.random.default_rng(1000 * n + s)
            X, y = sample(r, theta, n)
            m = BernoulliNaiveBayes(CANDIDATE_LABELS, CLASSES, alpha=1.0).fit(tagsets(X), [CLASSES[i] for i in y])
            maes.append(np.abs(m.theta_ - theta).mean())
            accs.append(np.mean(m.predict_proba(test_sets).argmax(1) == yt))
        rows.append([n, float(np.mean(maes)), float(np.std(maes)), float(np.mean(accs)),
                     float(bayes_acc - np.mean(accs))])
        mae_curve.append(float(np.mean(maes)))

    cols = ["n_train", "param MAE (mean)", "param MAE (std)", "test accuracy", "gap to Bayes-optimal"]
    print(f"Bayes-optimal accuracy on the held-out sample: {bayes_acc:.4f}")
    print_table(cols, rows)

    path = save_report("aml_nb_recovery", {
        "title": "Naive Bayes: parameter recovery and accuracy vs training-set size",
        "description": "Tag sets are sampled from the app's hand-crafted table; the learned model is fitted by MLE with "
                       "Laplace smoothing (alpha = 1). Parameter error shrinks as n grows and accuracy approaches the "
                       "Bayes-optimal classifier, which is what consistency of the maximum-likelihood estimator predicts.",
        "meta": {"seeds per size": SEEDS, "test samples": TEST_N, "vocabulary": len(CANDIDATE_LABELS),
                 "Bayes-optimal accuracy": round(bayes_acc, 4)},
        "table": {"columns": cols, "rows": rows},
        "curve": {"label": "Mean absolute parameter error vs n (log-spaced sizes)", "y": mae_curve},
        "notes": "Caveat: the data are synthetic and generated by a model that satisfies the naive independence "
                 "assumption exactly. Real CLIP tags are a top-5 selection, so independence is only approximate.",
    })
    print("saved", path)


if __name__ == "__main__":
    main()
